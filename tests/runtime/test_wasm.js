'use strict';
const assert=require('assert'),fs=require('fs'),path=require('path');
const file=path.join(__dirname,'../../apps/kxrxh_doodle_jump/ui.wasm');
assert(fs.existsSync(file),'Build the precompiled Rust UI before running the app');
const bytes=fs.readFileSync(file);
assert(WebAssembly.validate(bytes),'The shipped UI must be supported by this runtime');
const ui=require('../../apps/kxrxh_doodle_jump/ui');
const {Controls}=require('../../apps/kxrxh_doodle_jump/controls');
const {World}=require('../../apps/kxrxh_doodle_jump/world');
const c=new Controls(()=>true);
c.observe({frontRotaryEncoderOperation:0});
c.raw({frontRotaryEncoderOperation:4});
assert(c.take().tilt>0,'The Rust control core must queue a ring impulse');
ui.core.controls_reset(c._handle);
assert.deepStrictEqual(c.take(),{tilt:0,touches:[]},'The JS adapter must expose Rust-owned control state');
const world=new World();
const view=new Float64Array(ui.core.memory.buffer,ui.core.world_state(world._handle),2);
view[0]=31;view[1]=7;
assert.strictEqual(world.phase,31);assert.strictEqual(world.lean,7);
assert(ui.core.memory.buffer.byteLength<=256*1024,'The UI core needs bounded metadata memory');
const a=new Controls(()=>false),b=new Controls(()=>false);
a.tap(12,34);b.tap(56,78);
assert.deepStrictEqual(a.take().touches,[[0,0,12,34]]);
assert.deepStrictEqual(b.take().touches,[[0,0,56,78]],'Separate controllers retain separate queues');
const paper={width:480,height:512,u:(756%408+.2)/408,v:.0002,du:1/544,dv:1/960,alpha:.5};
const cv={alpha(){},clip(...rectangle){rectangle.forEach(value=>assert(!Object.is(value,-0),
    'Shared paper clips use canonical zero so unchanged native command buffers stay cached'));},image(){},line(){},noclip(){}};
new World().draw(cv,1920,720,{paper,sprites:{}},0,false,0);
let invalidCalls=0;
const invalid={alpha(){invalidCalls++;},clip(){invalidCalls++;},image(){invalidCalls++;},line(){invalidCalls++;},noclip(){invalidCalls++;}};
new World().draw(invalid,NaN,720,{paper:null,sprites:{}},0,false,1/60);
assert.strictEqual(invalidCalls,0,'An invalid width cannot submit malformed drawing commands');
console.log('Precompiled Rust WASM ownership, memory and runtime compatibility: passed');
